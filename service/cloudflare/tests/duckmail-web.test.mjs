import assert from "node:assert/strict";
import path from "node:path";
import { test } from "node:test";
import { chromium } from "playwright-core";
import { createHarness, PASSWORD } from "./runtime-harness.mjs";
import { duckMail, duckmailFixture } from "./duckmail-fixture.mjs";

test("Chrome: configure explicit public DuckMail, probe without a Key, allocate, page, safely read and extract without a client", { timeout: 90000 }, async () => {
  const f = await duckmailFixture({ anonymous: true }); let h, browser, page;
  try {
    h = await createHarness(f.bindings, true); const admin = await h.register("duckmail-web-admin");
    await h.db.prepare("INSERT INTO platform_admins VALUES (?,unixepoch())").bind(admin.id).run();
    browser = await chromium.launch({ executablePath: process.env.EASYEMAIL_CHROME_PATH ?? "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true });
    page = await browser.newPage({ viewport: { width: 1100, height: 1000 } }); page.setDefaultTimeout(10000);
    const errors = [], external = [];
    page.on("pageerror", error => errors.push(error.message));
    page.on("request", request => { if (!request.url().startsWith(h.baseUrl.origin)) external.push(request.url()); });
    await page.goto(h.baseUrl.href);
    await page.getByLabel("用户名", { exact: true }).fill("duckmail-web-admin");
    await page.getByLabel("密码", { exact: true }).fill(PASSWORD);
    await page.getByRole("button", { name: "登录", exact: true }).click();
    await page.getByRole("button", { name: "退出登录", exact: true }).waitFor();
    // Settle the initial mailbox screen's public-domain read before measuring admin actions.
    await page.getByRole("combobox", { name: "域名", exact: true }).locator("option").first().waitFor({ state: "attached" });
    const startupCalls = f.calls.length; assert.equal(startupCalls, 2);
    assert.ok(f.calls.every(call => call.method === "GET" && call.path === "/domains" && !call.headers.authorization));
    await page.getByRole("button", { name: "平台管理", exact: true }).click();
    await page.getByRole("heading", { name: "平台用量", exact: true }).waitFor();
    await page.getByRole("button", { name: "新增供应商", exact: true }).click();
    await page.getByLabel("实例 ID", { exact: true }).fill("extra-duck");
    await page.getByRole("combobox", { name: "供应商类型", exact: true }).selectOption("duckmail");
    await page.getByRole("combobox", { name: "上游访问方式", exact: true }).selectOption("anonymous");
    assert.equal(await page.getByLabel("发送渠道", { exact: true }).count(), 0);
    await page.getByLabel("API 地址", { exact: true }).fill(f.config.baseUrl);
    await page.getByLabel("启用供应商", { exact: true }).check();
    await page.getByLabel("域名白名单", { exact: true }).fill("duckmail.example.test");
    assert.equal(await page.getByLabel("供应商 API Key", { exact: true }).count(), 0);
    await page.getByRole("button", { name: "保存供应商", exact: true }).click();
    await page.getByRole("status").filter({ hasText: "供应商配置已保存" }).waitFor(); assert.equal(f.calls.length, startupCalls);
    await page.getByRole("button", { name: "探测 extra-duck", exact: true }).click();
    await page.getByRole("status").filter({ hasText: "extra-duck：接口探测通过" }).waitFor();
    assert.equal(f.calls.length, startupCalls + 2); assert.ok(f.calls.every(call => call.path === "/domains" && !call.headers.authorization));
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(h.directory, "duckmail-admin-mobile.png"), fullPage: true });
    await page.getByRole("button", { name: "邮箱管理", exact: true }).click();
    await page.getByRole("combobox", { name: "供应商", exact: true }).selectOption("extra-duck");
    await page.getByRole("combobox", { name: "域名", exact: true }).selectOption("duckmail.example.test");
    await page.getByRole("button", { name: "分配随机邮箱", exact: true }).click();
    await page.getByRole("heading", { name: "收件箱", exact: true }).waitFor();
    const mailbox = await h.db.prepare("SELECT * FROM mailboxes WHERE provider_id='extra-duck'").first(), account = f.accounts.get(mailbox.address);
    assert.equal(mailbox.expires_at - mailbox.created_at, 86400); assert.ok(account);
    f.messages.set(mailbox.address, Array.from({ length: 31 }, (_, n) => duckMail(account, n + 1)));
    await page.getByRole("button", { name: "刷新收信", exact: true }).click();
    await page.getByRole("button", { name: "继续同步下一页", exact: true }).click();
    await page.getByRole("button", { name: "继续同步下一页", exact: true }).waitFor({ state: "detached" });
    assert.equal((await h.db.prepare("SELECT COUNT(*) n FROM messages WHERE mailbox_id=?").bind(mailbox.id).first()).n, 31);
    await page.getByRole("button", { name: /^Duck verify \d+$/ }).first().click();
    await page.getByTestId("mail-body").waitFor();
    assert.equal(await page.getByTestId("mail-body").textContent(), "Your verification code is 735296.");
    await page.getByRole("button", { name: "安全 HTML", exact: true }).click();
    assert.equal(await page.locator('iframe[title="安全邮件正文"]').getAttribute("sandbox"), "");
    assert.equal(await page.frameLocator('iframe[title="安全邮件正文"]').locator("b").textContent(), "735296");
    assert.equal(await page.frameLocator('iframe[title="安全邮件正文"]').locator("script").count(), 0);
    assert.equal(await page.evaluate(() => window.duckExecuted), undefined);
    const attachments = page.getByRole("region", { name: "邮件附件", exact: true });
    assert.equal(await attachments.getByText("sample.txt", { exact: true }).count(), 1);
    assert.equal(await attachments.getByRole("button").count(), 0);
    await page.getByRole("button", { name: "纯文本", exact: true }).click();
    await page.getByRole("button", { name: "提取缓存邮件", exact: true }).click();
    assert.equal(await page.getByTestId("otp-code").first().textContent(), "735296");
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.getByTestId("mail-body").scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(h.directory, "duckmail-reader-mobile.png") });
    const text = await page.locator("body").innerText();
    for (const value of [account.token, account.password, "dk_synthetic_platform_key", "invalid.example"]) assert.equal(text.includes(value), false);
    assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0);
    await page.reload(); await page.getByRole("button", { name: mailbox.address, exact: true }).click();
    await page.getByRole("button", { name: /^Duck verify \d+$/ }).first().waitFor();
    assert.equal(f.calls.filter(call => call.path === "/accounts").length, 1);
    assert.equal(f.calls.some(call => call.path === "/exfiltrate"), false);
    assert.deepEqual(errors, []); assert.deepEqual(external, []);
    console.log(`DuckMail Chrome evidence: ${h.directory}`);
  } catch (error) {
    if (page) { console.error(await page.locator("body").ariaSnapshot()); await page.screenshot({ path: path.join(h.directory, "duckmail-failure.png"), fullPage: true }); }
    throw error;
  } finally { await browser?.close(); await h?.close(); await f.close(); }
});
