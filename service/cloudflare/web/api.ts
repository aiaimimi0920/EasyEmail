export class ApiError extends Error {
  constructor(public status: number, code: string) { super(code); }
}

export async function api<T>(path: string, method = "GET", body?: unknown, headers?: Record<string, string>, signal?: AbortSignal): Promise<T> {
  const response = await fetch(`/api/v1${path}`, {
    method, credentials: "same-origin", redirect: "error", cache: "no-store", signal,
    headers: { ...(body === undefined ? {} : { "content-type": "application/json" }), ...headers },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const value = await response.json();
  if (!response.ok) throw new ApiError(response.status, value.error?.code ?? "request_failed");
  return value as T;
}

